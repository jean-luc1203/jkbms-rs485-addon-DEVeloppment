const py=get('homeassistant/custom_components/smartphoton_glow_journal/__init__.py');
const pyPath=path.join(base,'homeassistant/custom_components/smartphoton_glow_journal/__init__.py');
const check=spawnSync('python3',['-c','import ast,sys; ast.parse(open(sys.argv[1], encoding="utf-8").read())',pyPath],{encoding:'utf8'});
assert.equal(check.status,0,'Python integration syntax error: '+check.stderr);
assert.match(py,/@websocket_api\.require_admin/);
assert.match(py,/@websocket_api\.websocket_command/);
assert.match(py,/@websocket_api\.async_response/);
assert.match(py,/hass\.async_add_executor_job\(_read_journal, hass\)/);
assert.match(py,/smartphoton_jkbms_multipack\/glow-journal-store\/global\/global\.json/);
assert.match(py,/MAX_FILE_BYTES = 1024 \* 1024/);
assert.match(py,/MAX_EVENTS = 250/);
assert.match(py,/f"\{DOMAIN\}\/list"/);
assert.ok(!/requests\.(get|post)|aiohttp\.ClientSession|http\.client/.test(py),'reader should never make network requests');
const viewer=get('rootfs/etc/smartphoton_jkbms_multipack/www/glow/journal.js');
new Function(viewer);
assert.match(viewer,/smartphoton_glow_journal\/list/);
